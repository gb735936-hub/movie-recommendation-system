''' movie recommendation systerm:

A Movie Recommendation System is a software system that suggests movies to users based
on their preferences, interests, viewing history, ratings, or similarities between movies.
'''


'''typers'''
'''There are 3 main types of Movie Recommendation Systems:

Content-Based Filtering:
Recommends movies similar to movies you already like, based on genre, actors, director, keywords, etc.
Example: You like action movies → it recommends similar action movies.

Collaborative Filtering:
Recommends movies based on what users with similar preferences liked.
Example: People who liked the same movies as you also liked another movie → it recommends that movie.

Hybrid Recommendation System:
Combines content-based + collaborative filtering to give better recommendations.
Example: Netflix-style systems can use both your viewing behavior and movie characteristics.'''